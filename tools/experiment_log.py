#!/usr/bin/env python
"""Catalogue every evaluated run as a Markdown table (no plotting, stdlib only).

Walks <root>/<group>/<tag>/seed<k>/metrics.json (layout of scripts/run_protocol.sh and
scripts/colab/run_soups.sh) and writes one row per (group, tag):
  n seeds, trainable params, selected epochs, Avg(D) (CDF-v2, DFD, DFDC, DFDCP),
  Avg(M7) (7 DF40 face-swap sets), FF++ test video AUC, per-dataset seed means,
  and the config keys that differ from the detector's base yaml.

    python tools/experiment_log.py --roots results_paper/results results_drive/BiasLN_runs2 \
        --out docs/experiment_table.md
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import statistics as st

D = ["Celeb-DF-v2", "DeepFakeDetection", "DFDC", "DFDCP"]
M = ["uniface_ff", "blendface_ff", "e4s_ff", "facedancer_ff", "fsgan_ff", "inswap_ff", "simswap_ff"]
SHORT = {"Celeb-DF-v2": "CDF", "DeepFakeDetection": "DFD", "DFDC": "DFDC", "DFDCP": "DFDCP",
         "uniface_ff": "Uni", "blendface_ff": "Blend", "e4s_ff": "E4S", "facedancer_ff": "FDan",
         "fsgan_ff": "FSGAN", "inswap_ff": "InSw", "simswap_ff": "SimSw"}
WATCH = ["tuning_mode", "tune_blocks", "param_roles", "ln_gamma_lr_scale", "feature_layers", "l2_norm",
         "lambda_anchor", "anchor_on", "backbone_lr", "label_smoothing", "lr", "batch_size", "nEpochs"]


def flat_cfg(path):
    out = {}
    try:
        import yaml  # optional
        c = yaml.safe_load(open(path))
    except Exception:
        return out
    for k in WATCH:
        if k in c:
            out[k] = c[k]
    opt = c.get("optimizer", {})
    if isinstance(opt, dict):
        for v in opt.values():
            if isinstance(v, dict) and "lr" in v:
                out["lr"] = v["lr"]
    fn = c.get("frame_num", {})
    if isinstance(fn, dict):
        out["frames_train"] = fn.get("train")
    return out


def mean_std(xs):
    if not xs:
        return ""
    if len(xs) == 1:
        return f"{xs[0]:.4f}"
    return f"{st.mean(xs):.4f} ± {st.stdev(xs):.4f}"


def collect(roots):
    runs = {}
    for root in roots:
        for f in glob.glob(os.path.join(root, "*", "*", "seed*", "metrics.json")):
            seed_dir = os.path.dirname(f)
            tag_dir = os.path.dirname(seed_dir)
            group = os.path.basename(os.path.dirname(tag_dir))
            key = (group, os.path.basename(tag_dir))
            seed = os.path.basename(seed_dir)[4:]
            try:
                m = json.load(open(f))["metrics"]
            except Exception:
                continue
            info = {}
            ri = os.path.join(seed_dir, "run_info.json")
            if os.path.exists(ri):
                try:
                    info = json.load(open(ri))
                except Exception:
                    pass
            cfg = flat_cfg(os.path.join(seed_dir, "config.yaml"))
            runs.setdefault(key, {})[seed] = (m, info, cfg)  # later roots override earlier ones
    return runs


def row(group, tag, seeds):
    def v(m, k):
        return m[k]["video_auc"] if k in m and "video_auc" in m[k] else None
    dvals, mvals, ff, per, ep, params = [], [], [], {k: [] for k in D + M}, [], set()
    cfg = {}
    for s, (m, info, c) in sorted(seeds.items()):
        d = [v(m, k) for k in D]
        if all(x is not None for x in d):
            dvals.append(sum(d) / 4)
        mm = [v(m, k) for k in M]
        if all(x is not None for x in mm):
            mvals.append(sum(mm) / 7)
        if v(m, "FaceForensics++") is not None:
            ff.append(v(m, "FaceForensics++"))
        for k in D + M:
            if v(m, k) is not None:
                per[k].append(v(m, k))
        sel = info.get("selected", {})
        if "epoch" in sel:
            ep.append(str(sel["epoch"]))
        tp = info.get("trainable_params", {}).get("trainable")
        if tp:
            params.add(tp)
        cfg = c or cfg
    pd = " ".join(f"{SHORT[k]} {st.mean(per[k]):.3f}" for k in D if per[k])
    pm = " ".join(f"{SHORT[k]} {st.mean(per[k]):.3f}" for k in M if per[k])
    cfgs = ", ".join(f"{k}={v}" for k, v in cfg.items() if v is not None)
    return (f"| {group} | {tag} | {','.join(sorted(seeds, key=str))} | "
            f"{'/'.join(f'{p:,}' for p in sorted(params)) or '–'} | {','.join(ep) or '–'} | "
            f"{mean_std(dvals)} | {mean_std(mvals)} | {mean_std(ff)} | {pd} | {pm} | {cfgs} |")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--roots", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    runs = collect(a.roots)
    lines = ["<!-- generated by tools/experiment_log.py -- do not edit by hand -->",
             "",
             f"{len(runs)} evaluated configurations. Video AUC; Avg(D) = mean of CDF-v2, DFD, DFDC, DFDCP; "
             "Avg(M7) = mean of the 7 DF40 face-swap sets; mean ± sample std over seeds; per-dataset values are seed means. "
             "Epoch = epoch selected on FF++ val (0-based). Empty Avg(M7) = DF40 not evaluated for that run.",
             "",
             "| Group | Tag | Seeds | Trainable | Sel. epoch | Avg(D) | Avg(M7) | FF++ | Cross-dataset | Cross-method | Config |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for (g, t) in sorted(runs):
        lines.append(row(g, t, runs[(g, t)]))
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {a.out}: {len(runs)} configurations")


if __name__ == "__main__":
    main()
