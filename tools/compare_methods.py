#!/usr/bin/env python
"""Score-level comparison of two detectors beyond the mean AUC (no GPU needed).

Reads <root>/<method>/seed<k>/scores/<dataset>.npz (video, score, label) and reports
  1. complementarity: error overlap at the EER threshold, and AUC of the score average
  2. operating points: ECE (15 bins), ACC@0.5, EER, FPR at TPR=95%, TPR at FPR=5%
  3. per-dataset AUC of both methods and the ensemble (FF++ subsets and DF40 methods included)
  4. seed stability: std over seeds per dataset
Scores of each method are first averaged over its seeds (per video), except for 4.

    python tools/compare_methods.py --root results_drive/BiasLN_runs2/anchor_val \
        --a biasln --b gend --seeds 1024 1 2 --out docs/compare_biasln_gend.md
"""
from __future__ import annotations

import argparse
import os

import numpy as np

DATASETS = ["Celeb-DF-v2", "DeepFakeDetection", "DFDC", "DFDCP",
            "uniface_ff", "blendface_ff", "e4s_ff", "facedancer_ff", "fsgan_ff", "inswap_ff", "simswap_ff",
            "FF-DF", "FF-F2F", "FF-FS", "FF-NT"]
CROSS_D = DATASETS[:4]
CROSS_M = DATASETS[4:11]


def auc(y, s):
    y = np.asarray(y).astype(bool)
    order = np.argsort(s, kind="mergesort")
    ranks = np.empty(len(s), float)
    ss = np.asarray(s)[order]
    i = 0
    r = np.arange(1, len(s) + 1, dtype=float)
    while i < len(s):  # average ranks of ties
        j = i
        while j + 1 < len(s) and ss[j + 1] == ss[i]:
            j += 1
        r[i:j + 1] = (i + j + 2) / 2.0
        i = j + 1
    ranks[order] = r
    npos, nneg = y.sum(), (~y).sum()
    return (ranks[y].sum() - npos * (npos + 1) / 2) / (npos * nneg)


def roc_points(y, s):
    y = np.asarray(y).astype(bool)
    thr = np.unique(s)[::-1]
    tpr = np.array([(s[y] >= t).mean() for t in thr])
    fpr = np.array([(s[~y] >= t).mean() for t in thr])
    return thr, tpr, fpr


def operating(y, s):
    thr, tpr, fpr = roc_points(y, s)
    fnr = 1 - tpr
    k = np.argmin(np.abs(fnr - fpr))
    eer, t_eer = (fnr[k] + fpr[k]) / 2, thr[k]
    fpr95 = fpr[np.argmax(tpr >= 0.95)] if (tpr >= 0.95).any() else 1.0
    ok = fpr <= 0.05
    tpr05 = tpr[ok].max() if ok.any() else 0.0
    acc = ((s >= 0.5) == y.astype(bool)).mean()
    bins = np.linspace(0, 1, 16)
    pred = (s >= 0.5).astype(int)
    conf = np.where(pred == 1, s, 1 - s)
    correct = pred == y
    ece = 0.0
    for lo, hi in zip(bins[:-1], bins[1:]):
        m = (conf > lo) & (conf <= hi) if lo > 0 else (conf >= lo) & (conf <= hi)
        if m.any():
            ece += m.mean() * abs(correct[m].mean() - conf[m].mean())
    return dict(eer=eer, t_eer=t_eer, fpr95=fpr95, tpr_at_fpr5=tpr05, acc05=acc, ece=ece)


def load(root, method, seed, ds):
    p = f"{root}/{method}/seed{seed}/scores/{ds}.npz"
    if not os.path.exists(p):
        return None
    d = np.load(p, allow_pickle=True)
    return {str(v): (float(s), int(l)) for v, s, l in zip(d["video"], d["score"], d["label"])}


def seed_avg(root, method, seeds, ds):
    runs = [r for r in (load(root, method, s, ds) for s in seeds) if r]
    if not runs:
        return None
    common = set.intersection(*[set(r) for r in runs])
    vids = sorted(common)
    y = np.array([runs[0][v][1] for v in vids])
    s = np.mean([[r[v][0] for v in vids] for r in runs], axis=0)
    return vids, y, s, [np.array([r[v][0] for v in vids]) for r in runs]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--a", default="biasln")
    ap.add_argument("--b", default="gend")
    ap.add_argument("--seeds", nargs="+", default=["1024", "1", "2"])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    A, B = a.a, a.b
    L = [f"# {A} vs {B}: score-level analysis", "",
         f"Scores averaged over seeds {', '.join(a.seeds)} per video (except the seed-stability table). "
         "Generated by `tools/compare_methods.py`.", ""]

    comp, opsA, opsB, stab = [], [], [], []
    avg = {k: {A: [], B: [], "ens": []} for k in ("D", "M")}
    for ds in DATASETS:
        ra, rb = seed_avg(a.root, A, a.seeds, ds), seed_avg(a.root, B, a.seeds, ds)
        if not ra or not rb:
            continue
        common = sorted(set(ra[0]) & set(rb[0]))
        ia = {v: i for i, v in enumerate(ra[0])}
        ib = {v: i for i, v in enumerate(rb[0])}
        y = ra[1][[ia[v] for v in common]]
        sa = ra[2][[ia[v] for v in common]]
        sb = rb[2][[ib[v] for v in common]]
        ens = (sa + sb) / 2
        auc_a, auc_b, auc_e = auc(y, sa), auc(y, sb), auc(y, ens)
        oa, ob = operating(y, sa), operating(y, sb)
        ea = (sa >= oa["t_eer"]) != y.astype(bool)
        eb = (sb >= ob["t_eer"]) != y.astype(bool)
        n_err_union = (ea | eb).sum()
        jacc = (ea & eb).sum() / max(n_err_union, 1)
        rho = np.corrcoef(sa, sb)[0, 1]
        comp.append(f"| {ds} | {len(y)} | {auc_a:.4f} | {auc_b:.4f} | **{auc_e:.4f}** | {auc_e - max(auc_a, auc_b):+.4f} | "
                    f"{(ea & ~eb).sum()} | {(eb & ~ea).sum()} | {(ea & eb).sum()} | {jacc:.2f} | {rho:.2f} |")
        for name, o, dst in ((A, oa, opsA), (B, ob, opsB)):
            dst.append((ds, o))
        sa_seeds = [auc(ra[1], s) for s in ra[3]]
        sb_seeds = [auc(rb[1], s) for s in rb[3]]
        stab.append(f"| {ds} | {np.std(sa_seeds, ddof=1):.4f} | {np.std(sb_seeds, ddof=1):.4f} | "
                    f"{max(sa_seeds) - min(sa_seeds):.4f} | {max(sb_seeds) - min(sb_seeds):.4f} |")
        grp = "D" if ds in CROSS_D else "M" if ds in CROSS_M else None
        if grp:
            avg[grp][A].append(auc_a); avg[grp][B].append(auc_b); avg[grp]["ens"].append(auc_e)

    L += ["## 1. Complementarity", "",
          "Errors at each method's own EER threshold. Jaccard = shared errors / union of errors; "
          "rho = Pearson correlation of the video scores. Ens = mean of the two score vectors.", "",
          f"| Dataset | videos | AUC {A} | AUC {B} | AUC ens | ens - best | only {A} wrong | only {B} wrong | both wrong | Jaccard | rho |",
          "|---|---|---|---|---|---|---|---|---|---|---|"] + comp
    for g, name in (("D", "Avg(D)"), ("M", "Avg(M)")):
        if avg[g][A]:
            L.append(f"| **{name}** | | {np.mean(avg[g][A]):.4f} | {np.mean(avg[g][B]):.4f} | **{np.mean(avg[g]['ens']):.4f}** | "
                     f"{np.mean(avg[g]['ens']) - max(np.mean(avg[g][A]), np.mean(avg[g][B])):+.4f} | | | | | |")
    L += ["", "## 2. Operating points (seed-averaged scores)", "",
          "ECE: 15-bin expected calibration error of the fake probability at threshold 0.5. "
          "FPR@TPR95: fraction of real videos flagged when 95% of fakes are caught. Lower is better except ACC and TPR.", "",
          f"| Dataset | ACC@0.5 {A} | ACC@0.5 {B} | EER {A} | EER {B} | FPR@TPR95 {A} | FPR@TPR95 {B} | "
          f"TPR@FPR5 {A} | TPR@FPR5 {B} | ECE {A} | ECE {B} |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for (ds, oa), (_, ob) in zip(opsA, opsB):
        L.append(f"| {ds} | {oa['acc05']:.3f} | {ob['acc05']:.3f} | {oa['eer']:.3f} | {ob['eer']:.3f} | "
                 f"{oa['fpr95']:.3f} | {ob['fpr95']:.3f} | {oa['tpr_at_fpr5']:.3f} | {ob['tpr_at_fpr5']:.3f} | "
                 f"{oa['ece']:.3f} | {ob['ece']:.3f} |")
    for keyset, name in ((CROSS_D, "mean over cross-dataset"), (CROSS_M, "mean over DF40")):
        ka = [o for d, o in opsA if d in keyset]; kb = [o for d, o in opsB if d in keyset]
        if ka:
            m = lambda xs, k: np.mean([x[k] for x in xs])
            L.append(f"| **{name}** | {m(ka,'acc05'):.3f} | {m(kb,'acc05'):.3f} | {m(ka,'eer'):.3f} | {m(kb,'eer'):.3f} | "
                     f"{m(ka,'fpr95'):.3f} | {m(kb,'fpr95'):.3f} | {m(ka,'tpr_at_fpr5'):.3f} | {m(kb,'tpr_at_fpr5'):.3f} | "
                     f"{m(ka,'ece'):.3f} | {m(kb,'ece'):.3f} |")
    L += ["", "## 3. Seed stability (per-seed AUC)", "",
          f"| Dataset | std {A} | std {B} | range {A} | range {B} |", "|---|---|---|---|---|"] + stab
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
