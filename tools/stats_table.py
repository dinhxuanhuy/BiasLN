#!/usr/bin/env python
"""Paired significance (t-test, Holm-corrected) and TOST equivalence table for the revised manuscript.

    python tools/stats_table.py --results results_paper/results6 --out paper/revision_v2/generated
"""
import argparse, glob, json, os
import numpy as np
from scipy import stats

D = ["Celeb-DF-v2", "DeepFakeDetection", "DFDC", "DFDCP"]
M = ["uniface_ff", "blendface_ff", "e4s_ff", "facedancer_ff", "fsgan_ff", "inswap_ff", "simswap_ff"]
NAMES = {"ln_l2": "LN only", "bitfit": "BitFit", "biasln": "BiasLN", "gend": "GenD", "glr3": "BiasLN $\\gamma$-lr$\\times$3",
         "effort": "Effort", "lora": "LoRA"}
PAIRS = [("ln_l2", "bitfit"), ("ln_l2", "biasln"), ("ln_l2", "gend"), ("biasln", "bitfit"),
         ("gend", "biasln"), ("gend", "bitfit"), ("glr3", "biasln")]
MARGIN = 0.01


def per_seed(results, tag, keys):
    out = {}
    for f in sorted(glob.glob(os.path.join(results, "*", tag, "seed*", "metrics.json"))):
        seed = f.split(os.sep)[-2]
        if seed in out:
            continue
        m = json.load(open(f))["metrics"]
        if all(k in m for k in keys):
            out[seed] = float(np.mean([m[k]["video_auc"] for k in keys]))
    return out


def holm(ps):
    order = np.argsort(ps); adj = np.empty(len(ps)); run = 0.0
    for r, i in enumerate(order):
        run = max(run, (len(ps) - r) * ps[i]); adj[i] = min(1.0, run)
    return adj


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--results", required=True); ap.add_argument("--out", required=True)
    a = ap.parse_args()
    rows, pvals, tvals = [], [], []
    for x, y in PAIRS:
        row = [x, y]
        for keys in (D, M):
            A, B = per_seed(a.results, x, keys), per_seed(a.results, y, keys)
            s = sorted(set(A) & set(B)); d = np.array([A[k] - B[k] for k in s])
            p = stats.ttest_rel([A[k] for k in s], [B[k] for k in s]).pvalue
            tost = max(stats.ttest_1samp(d, -MARGIN, alternative="greater").pvalue,
                       stats.ttest_1samp(d, MARGIN, alternative="less").pvalue)
            row.append(dict(n=len(s), diff=d.mean(), p=p, tost=tost, wins=int((d > 0).sum())))
            pvals.append(p); tvals.append(tost)
        rows.append(row)
    adj, tadj = holm(np.array(pvals)), holm(np.array(tvals))
    k = 0
    for row in rows:
        for c in row[2:]:
            c["holm"] = adj[k]; c["tost_holm"] = tadj[k]; k += 1
    fp = lambda v: "$<$0.001" if v < 0.001 else f"{v:.3f}"
    lines = ["% generated by tools/stats_table.py -- do not edit",
             "\\begin{tabular}{l c rrrrc rrrrc}", "\\toprule",
             "& & \\multicolumn{5}{c}{\\textbf{Avg(D)}} & \\multicolumn{5}{c}{\\textbf{Avg(M)}} \\\\",
             "\\cmidrule(lr){3-7} \\cmidrule(lr){8-12}",
             "\\textbf{A vs.\\ B} & $n$ & $\\Delta$ & $p$ & $p_{\\mathrm{Holm}}$ & $p^{\\mathrm{Holm}}_{\\mathrm{TOST}}$ & wins & $\\Delta$ & $p$ & $p_{\\mathrm{Holm}}$ & $p^{\\mathrm{Holm}}_{\\mathrm{TOST}}$ & wins \\\\",
             "\\midrule"]
    for x, y, cd, cm in rows:
        cells = []
        for c in (cd, cm):
            bold = lambda t, cond: f"\\textbf{{{t}}}" if cond else t
            cells += [f"{c['diff']:+.4f}", fp(c["p"]), bold(fp(c["holm"]), c["holm"] < 0.05),
                      bold(fp(c["tost_holm"]), c["tost_holm"] < 0.05), f"{c['wins']}/{c['n']}"]
        lines.append(f"{NAMES[x]} vs.\\ {NAMES[y]} & {cd['n']} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    os.makedirs(a.out, exist_ok=True)
    open(os.path.join(a.out, "tab_stats.tex"), "w").write("\n".join(lines) + "\n")
    for x, y, cd, cm in rows:
        print(f"{x}-{y}: D {cd['diff']:+.4f} p={cd['p']:.3f} holm={cd['holm']:.3f} tost={cd['tost']:.3f} | "
              f"M {cm['diff']:+.4f} p={cm['p']:.3f} holm={cm['holm']:.3f} tost={cm['tost']:.3f} tostH={cm['tost_holm']:.3f} | DtostH={cd['tost_holm']:.3f}")


if __name__ == "__main__":
    main()
