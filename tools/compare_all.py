#!/usr/bin/env python
"""Multi-method version of tools/compare_methods.py (CPU only).

For every method: seed-averaged AUC, ACC@0.5, EER, FPR@TPR95, TPR@FPR5, ECE (means over the
cross-dataset and the DF40 sets) and the seed std of the per-dataset AUC. For every pair:
AUC of the averaged scores (Avg(D), Avg(M)) and the share of common errors (Jaccard at the EER
threshold, mean over the cross-dataset sets).

    python tools/compare_all.py --root results_drive/BiasLN_runs2/anchor_val \
        --methods biasln bitfit gend effort fullft --out docs/compare_all.md
"""
from __future__ import annotations

import argparse
import itertools
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from compare_methods import CROSS_D, CROSS_M, auc, operating, seed_avg  # noqa: E402

NAMES = {"biasln": "BiasLN", "bitfit": "BitFit", "gend": "GenD", "effort": "Effort",
         "fullft": "Full FT", "linprobe": "Linear probe", "lora": "LoRA", "glr3": "BiasLN γ-lr×3"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--methods", nargs="+", required=True)
    ap.add_argument("--seeds", nargs="+", default=["1024", "1", "2"])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    M = a.methods
    data = {}  # (method, ds) -> {vid: (y, s)}, plus per-seed AUCs
    nseed = {}
    for m in M:
        for ds in CROSS_D + CROSS_M:
            r = seed_avg(a.root, m, a.seeds, ds)
            if r:
                vids, y, s, per = r
                data[(m, ds)] = (dict(zip(vids, zip(y, s))), [auc(y, p) for p in per])
                nseed[m] = len(per)

    def arrays(m, ds, vids):
        d = data[(m, ds)][0]
        return np.array([d[v][0] for v in vids]), np.array([d[v][1] for v in vids])

    L = ["# Score-level comparison of all re-trained methods", "",
         f"Seeds {', '.join(a.seeds)} (n per method in the table). Scores are averaged over seeds per video, "
         "so AUC here is the AUC of the seed ensemble, not the mean of per-seed AUCs used in the paper tables. "
         "Generated by `tools/compare_all.py`.", "",
         "## 1. Operating points (mean over the 4 cross-dataset sets | mean over the 7 DF40 sets)", "",
         "| Method | n | AUC | ACC@0.5 | EER ↓ | FPR@TPR95 ↓ | TPR@FPR5 | ECE ↓ | seed std of AUC ↓ |",
         "|---|---|---|---|---|---|---|---|---|"]
    for m in M:
        cells = []
        for grp in (CROSS_D, CROSS_M):
            ops, aucs, stds = [], [], []
            for ds in grp:
                if (m, ds) not in data:
                    continue
                d, per = data[(m, ds)]
                vids = sorted(d)
                y, s = arrays(m, ds, vids)
                ops.append(operating(y, s)); aucs.append(auc(y, s))
                if len(per) > 1:
                    stds.append(np.std(per, ddof=1))
            if not ops:
                cells.append(None); continue
            mean = lambda k: np.mean([o[k] for o in ops])
            cells.append((np.mean(aucs), mean("acc05"), mean("eer"), mean("fpr95"), mean("tpr_at_fpr5"),
                          mean("ece"), np.mean(stds) if stds else float("nan")))
        row = f"| {NAMES.get(m, m)} | {nseed.get(m, 0)} |"
        for k in range(7):
            vals = [f"{c[k]:.3f}" if c and not np.isnan(c[k]) else "–" for c in cells]
            row += f" {vals[0]} \\| {vals[1]} |"
        L.append(row)

    L += ["", "## 2. Pairwise ensembles (mean of the two seed-averaged score vectors)", "",
          "Ens AUC is the Avg(D) | Avg(M) of the pair; gain = ens − better single method. "
          "Jaccard = shared errors / union of errors at each method's EER threshold, mean over the cross-dataset sets "
          "(low = the two methods fail on different videos).", "",
          "| Pair | Ens Avg(D) | gain D | Ens Avg(M) | gain M | Jaccard (D) | score corr (D) |",
          "|---|---|---|---|---|---|---|"]
    for p, q in itertools.combinations(M, 2):
        res = {}
        jac, rho = [], []
        for gname, grp in (("D", CROSS_D), ("M", CROSS_M)):
            e, sp, sq = [], [], []
            for ds in grp:
                if (p, ds) not in data or (q, ds) not in data:
                    continue
                vids = sorted(set(data[(p, ds)][0]) & set(data[(q, ds)][0]))
                y, s1 = arrays(p, ds, vids)
                _, s2 = arrays(q, ds, vids)
                e.append(auc(y, (s1 + s2) / 2)); sp.append(auc(y, s1)); sq.append(auc(y, s2))
                if gname == "D":
                    o1, o2 = operating(y, s1), operating(y, s2)
                    e1 = (s1 >= o1["t_eer"]) != y.astype(bool)
                    e2 = (s2 >= o2["t_eer"]) != y.astype(bool)
                    jac.append((e1 & e2).sum() / max((e1 | e2).sum(), 1))
                    rho.append(np.corrcoef(s1, s2)[0, 1])
            res[gname] = (np.mean(e), np.mean(e) - max(np.mean(sp), np.mean(sq))) if e else (np.nan, np.nan)
        L.append(f"| {NAMES.get(p, p)} + {NAMES.get(q, q)} | {res['D'][0]:.4f} | {res['D'][1]:+.4f} | "
                 f"{res['M'][0]:.4f} | {res['M'][1]:+.4f} | {np.mean(jac):.2f} | {np.mean(rho):.2f} |")
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    open(a.out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
